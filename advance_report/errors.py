"""Исключения приложения.

Смысл разделения: неверные данные и дефект программы — разные ситуации с
разными кодами возврата. Данные противоречат формату — отчёт не строим и
честно падаем (лучше не выдать цифру, чем выдать неверную). Нарушен
внутренний инвариант — это баг, и его тоже нельзя замалчивать.
"""

from __future__ import annotations


class DataError(Exception):
    """Данные из ``data/`` не соответствуют формату: считать отчёт нельзя.

    Текст исключения предназначен бухгалтеру и программисту: в нём всегда
    есть файл, номер строки и колонка, к которым относится проблема.
    """


